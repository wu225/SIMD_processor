"""Offline fixtures; stdlib only. No Python or floating point needed on target."""
import argparse
import math
from pathlib import Path


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--taps', type=int, choices=(16, 32, 64), default=32)
    args = parser.parse_args()
    length = args.taps
    h = []
    for k in range(length):
        z = 0.2 * (k - (length - 1) / 2)
        sinc = 1.0 if z == 0 else math.sin(math.pi * z) / (math.pi * z)
        h.append(0.2 * sinc * (0.54 - 0.46 * math.cos(2 * math.pi * k / (length - 1))))
    total = sum(h)
    h = [v / total for v in h]
    q31 = [round(v * (1 << 31)) for v in h]
    tables = []
    bounds = []
    for width, fx, fh in ((8, 3, 6), (16, 7, 10), (32, 15, 15)):
        qh = [v // (1 << (31 - fh)) for v in q31]
        product_bound = (1 << fx) * max(map(abs, qh))
        acc_bound = (1 << fx) * sum(map(abs, qh))
        assert product_bound < (1 << (width - 1)), (width, product_bound)
        assert acc_bound < (1 << 31), (width, acc_bound)
        tables.append(qh)
        bounds.append((product_bound, acc_bound))
    tone = [round((0.6 * math.sin(2 * math.pi * 0.03 * n)
                   + 0.2 * math.sin(2 * math.pi * 0.30 * n)) * 32768)
            for n in range(100)]
    lines = ['/* Generated by generate_fixture.py. Hamming LPF fc/fs=0.1.',
             ' * Q31 source coefficients: RNE; lower formats: arithmetic truncation.',
             ' * MODE8 Fx/Fh=3/6; MODE16=7/10; MODE32=15/15. */',
             '#ifndef FIR_FIXTURE_H', '#define FIR_FIXTURE_H',
             f'#define FIR_TAPS {length}', '#define FIR_TONE_PERIOD 100',
             'static const int fir_coeff_fixture[3][FIR_TAPS] = {']
    for values in tables:
        lines.append('    {' + ', '.join(map(str, values)) + '},')
    lines += ['};', 'static const int fir_product_bound[3] = {'
              + ', '.join(str(b[0]) for b in bounds) + '};',
              'static const int fir_acc_bound[3] = {'
              + ', '.join(str(b[1]) for b in bounds) + '};',
              'static const int fir_tone_q15[FIR_TONE_PERIOD] = {']
    for i in range(0, 100, 10):
        lines.append('    ' + ', '.join(map(str, tone[i:i + 10])) + ',')
    lines += ['};', '#endif', '']
    path = Path(__file__).with_name('fir_fixture.h')
    path.write_text('\n'.join(lines), encoding='utf-8')
    print(f'Wrote {path.name}: taps={length}, bounds={bounds}')


if __name__ == '__main__':
    main()
